-- =========================================
-- CKAVOX WEBSITE DATABASE
-- =========================================

create table if not exists public.ckavox_content (
    id bigint generated by default as identity primary key,
    title text not null,
    description text default '',
    category text not null default 'News',
    content_type text not null default 'article',
    image_url text default '',
    media_url text default '',
    published boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.ckavox_slides (
    id bigint generated by default as identity primary key,
    title text not null,
    subtitle text default '',
    image_url text not null,
    link_url text default '',
    sort_order integer not null default 0,
    active boolean not null default true,
    created_at timestamptz not null default now()
);

-- =========================================
-- ENABLE ROW LEVEL SECURITY
-- =========================================

alter table public.ckavox_content
enable row level security;

alter table public.ckavox_slides
enable row level security;

-- =========================================
-- PUBLIC CONTENT ACCESS
-- =========================================

drop policy if exists "Public can read published content"
on public.ckavox_content;

create policy "Public can read published content"
on public.ckavox_content
for select
to anon, authenticated
using (published = true);

drop policy if exists "Public can read active slides"
on public.ckavox_slides;

create policy "Public can read active slides"
on public.ckavox_slides
for select
to anon, authenticated
using (active = true);

